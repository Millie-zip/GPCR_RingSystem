from gpcr_ringgen.models.diffusion.schedules import DDPMNoiseSchedule
from gpcr_ringgen.models.diffusion.state import initialize_stage3_state
from gpcr_ringgen.models.diffusion.transitions import q_sample
from gpcr_ringgen.utils.seed import make_torch_generator


@dataclass(frozen=True)
class RingSidechainClassConfig:
    """Categorical vocabulary sizes for Route-A graph diffusion.

    Bond state zero is reserved for ``NO_BOND``. Atom counts are generated by
    the separate Route-A count model, so atom types do not contain ``NO_ATOM``.
    """

    num_atom_types: int
    num_bond_states: int
    num_formal_charge_types: int
    num_chirality_types: int

    def __post_init__(self) -> None:
        for name in (
            "num_atom_types",
            "num_bond_states",
            "num_formal_charge_types",
            "num_chirality_types",
        ):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int):
                raise TypeError(f"{name} must be an integer")
            if value < 2:
                raise ValueError(f"{name} must be at least 2")
        if self.num_bond_states < 3:
            raise ValueError(
                "num_bond_states must include NO_BOND and at least two real bond classes"
            )

    @classmethod
    def from_mapping(cls, config: Mapping[str, Any]) -> "RingSidechainClassConfig":
        """Load Route-A categorical sizes from ``route_a.class_counts``."""

        route_a = config.get("route_a")
        if not isinstance(route_a, Mapping):
            raise TypeError("route_a config must be a mapping")
        values = route_a.get("class_counts")
        if not isinstance(values, Mapping):
            raise TypeError("route_a.class_counts must be a mapping")
        required = (
            "num_atom_types",
            "num_bond_states",
            "num_formal_charge_types",
            "num_chirality_types",
        )
        missing = [name for name in required if name not in values]
        if missing:
            raise KeyError("missing Route-A class counts: " + ", ".join(missing))
        return cls(**{name: values[name] for name in required})


@dataclass(frozen=True)
class RingSidechainForwardOutput:
    """Forward targets for Route-A ring-conditioned joint diffusion."""

    noisy_state: Stage3DiffusionState
    coordinate_noise: Tensor
    clean_atom_types: Tensor
    clean_bond_types: Tensor
    clean_formal_charge_types: Tensor
    clean_chiralities: Tensor
    bond_loss_mask: Tensor
    outer_atom_mask: Tensor

    def validate(self, classes: RingSidechainClassConfig) -> None:
        self.noisy_state.validate()
        state = self.noisy_state
        for name, values, expected_shape in (
            ("coordinate_noise", self.coordinate_noise, state.coordinates.shape),
            ("clean_atom_types", self.clean_atom_types, state.atom_features.shape[:2]),
            ("clean_bond_types", self.clean_bond_types, state.edge_features.shape[:2]),
            (
                "clean_formal_charge_types",
                self.clean_formal_charge_types,
                state.atom_features.shape[:2],
            ),
            ("clean_chiralities", self.clean_chiralities, state.atom_features.shape[:2]),
        ):
            if tuple(values.shape) != tuple(expected_shape):
                raise ValueError(f"{name} has an invalid shape")
        if self.bond_loss_mask.shape != state.mask.edge_mask.shape:
            raise ValueError("bond_loss_mask must have shape [B, E]")
        if self.outer_atom_mask.shape != state.mask.atom_mask.shape:
            raise ValueError("outer_atom_mask must have shape [B, N]")
        if self.bond_loss_mask.dtype != torch.bool or self.outer_atom_mask.dtype != torch.bool:
            raise TypeError("Route-A loss masks must have dtype torch.bool")
        if state.atom_types is None or state.bond_types is None:
            raise ValueError("Route-A state requires atom_types and bond_types")
        if state.formal_charge_types is None or state.chiralities is None:
            raise ValueError("Route-A state requires charge and chirality labels")
        ranges = (
            (state.atom_types, state.mask.atom_mask, classes.num_atom_types),
            (state.bond_types, state.mask.edge_mask, classes.num_bond_states),
            (
                state.formal_charge_types,
                state.mask.atom_mask,
                classes.num_formal_charge_types,
            ),
            (state.chiralities, state.mask.atom_mask, classes.num_chirality_types),
        )
        for values, mask, num_classes in ranges:
            valid = values.masked_select(mask)
            if valid.numel() and bool(((valid < 0) | (valid >= num_classes)).any()):
                raise ValueError("Route-A categorical state is outside its vocabulary")


def _route_masks(state: Stage3DiffusionState) -> tuple[Tensor, Tensor, Tensor, Tensor]:
    ring_atom = state.mask.ring_atom_mask
    ring_pair = state.mask.ring_pair_mask
    ring_edge = state.mask.ring_edge_mask
    if ring_atom is None or ring_pair is None or ring_edge is None:
        raise ValueError("Route A requires all ring masks")
    outer_atom = state.mask.atom_mask & ~ring_atom
    generative_edge = state.mask.edge_mask & ~ring_pair
    bond_loss_mask = ring_edge | generative_edge
    return outer_atom, ring_pair, ring_edge, bond_loss_mask


def _validate_clean_route_state(
    state: Stage3DiffusionState,
    classes: RingSidechainClassConfig,
) -> tuple[Tensor, Tensor, Tensor, Tensor]:
    state.validate()
    if state.atom_types is None or state.bond_types is None:
        raise ValueError("Route A requires atom_types and bond_types")
    if state.formal_charge_types is None or state.chiralities is None:
        raise ValueError("Route A requires formal_charge_types and chiralities")
    outer_atom, ring_pair, ring_edge, bond_loss_mask = _route_masks(state)
    if bool((state.bond_types.masked_select(ring_edge) == 0).any()):
        raise ValueError("fixed ring edges cannot use NO_BOND category zero")
    fixed_ring_nonedge = ring_pair & ~ring_edge
    if bool((state.bond_types.masked_select(fixed_ring_nonedge) != 0).any()):
        raise ValueError("fixed ring non-edges must use NO_BOND category zero")
    for name, values, mask, num_classes in (
        ("atom_types", state.atom_types, state.mask.atom_mask, classes.num_atom_types),
        ("bond_types", state.bond_types, state.mask.edge_mask, classes.num_bond_states),
        (
            "formal_charge_types",
            state.formal_charge_types,
            state.mask.atom_mask,
            classes.num_formal_charge_types,
        ),
        ("chiralities", state.chiralities, state.mask.atom_mask, classes.num_chirality_types),
    ):
        valid = values.masked_select(mask)
        if valid.numel() and bool(((valid < 0) | (valid >= num_classes)).any()):
            raise ValueError(f"{name} is outside its configured vocabulary")
    return outer_atom, ring_pair, ring_edge, bond_loss_mask


def _sample_nonzero_categories(
    mask: Tensor,
    num_classes: int,
    *,
    generator: torch.Generator | None,
) -> Tensor:
    if num_classes < 2:
        raise ValueError("nonzero categorical vocabulary needs at least two classes")
    return (
        sample_uniform_categories(mask, num_classes - 1, generator=generator) + 1
    ) * mask.to(torch.long)


def _q_sample_nonzero(
    clean_labels: Tensor,
    timestep: Tensor,
    schedule: DDPMNoiseSchedule,
    mask: Tensor,
    num_classes: int,
    *,
    generator: torch.Generator | None,
) -> Tensor:
    shifted = torch.where(mask, clean_labels - 1, torch.zeros_like(clean_labels))
    noisy = q_sample_categorical(
        shifted,
        timestep,
        schedule,
        mask,
        num_classes - 1,
        generator=generator,
    )
    return (noisy + 1) * mask.to(torch.long)


def q_sample_ring_sidechain(
    state: Stage3DiffusionState,
    timestep: Tensor,
    schedule: DDPMNoiseSchedule,
    classes: RingSidechainClassConfig,
    *,
    coordinate_noise: Tensor | None = None,
    generator: torch.Generator | None = None,
) -> RingSidechainForwardOutput:
    """Corrupt Route-A variables while preserving ring existence and labels.

    Coordinates and atom types are corrupted for every real atom. Bond states
    are corrupted on fixed-present ring edges and every candidate pair touching
    an outer atom. Ring non-edges remain ``NO_BOND``. Formal charge and
    chirality are corrupted only outside the ring core.
    """

    if not isinstance(classes, RingSidechainClassConfig):
        raise TypeError("classes must be a RingSidechainClassConfig")
    outer_atom, ring_pair, ring_edge, bond_loss_mask = _validate_clean_route_state(
        state, classes
    )
    coordinate_output = q_sample(
        state,
        timestep,
        schedule,
        noise=coordinate_noise,
        generator=generator if coordinate_noise is None else None,
    )
    noisy_atom = q_sample_categorical(
        state.atom_types,
        timestep,
        schedule,
        state.mask.atom_mask,
        classes.num_atom_types,
        generator=generator,
    )
    generative_edge = state.mask.edge_mask & ~ring_pair
    noisy_bond = torch.zeros_like(state.bond_types)
    noisy_bond = torch.where(
        generative_edge,
        q_sample_categorical(
            torch.where(generative_edge, state.bond_types, torch.zeros_like(state.bond_types)),
            timestep,
            schedule,
            generative_edge,
            classes.num_bond_states,
            generator=generator,
        ),
        noisy_bond,
    )
    noisy_bond = torch.where(
        ring_edge,
        _q_sample_nonzero(
            state.bond_types,
            timestep,
            schedule,
            ring_edge,
            classes.num_bond_states,
            generator=generator,
        ),
        noisy_bond,
    )
    noisy_charge = torch.where(
        outer_atom,
        q_sample_categorical(
            torch.where(
                outer_atom,
                state.formal_charge_types,
                torch.zeros_like(state.formal_charge_types),
            ),
            timestep,
            schedule,
            outer_atom,
            classes.num_formal_charge_types,
            generator=generator,
        ),
        state.formal_charge_types,
    )
    noisy_chirality = torch.where(
        outer_atom,
        q_sample_categorical(
            torch.where(
                outer_atom,
                state.chiralities,
                torch.zeros_like(state.chiralities),
            ),
            timestep,
            schedule,
            outer_atom,
            classes.num_chirality_types,
            generator=generator,
        ),
        state.chiralities,
    )
    noisy_state = replace(
        coordinate_output.noisy_state,
        atom_types=noisy_atom,
        bond_types=noisy_bond,
        formal_charge_types=noisy_charge,
        chiralities=noisy_chirality,
    )
    output = RingSidechainForwardOutput(
        noisy_state=noisy_state,
        coordinate_noise=coordinate_output.noise,
        clean_atom_types=state.atom_types.clone(),
        clean_bond_types=state.bond_types.clone(),
        clean_formal_charge_types=state.formal_charge_types.clone(),
        clean_chiralities=state.chiralities.clone(),
        bond_loss_mask=bond_loss_mask,
        outer_atom_mask=outer_atom,
    )
    output.validate(classes)
    return output


def initialize_ring_sidechain_state(
    stage3_input: Stage3Input,
    schedule: DDPMNoiseSchedule,
    classes: RingSidechainClassConfig,
    *,
    seed: int,
) -> Stage3DiffusionState:
    """Initialize Route-A categorical priors after the outer count is sampled."""

    state = initialize_stage3_state(
        stage3_input,
        seed=seed,
        timestep=schedule.num_timesteps - 1,
    )
    outer_atom, ring_pair, ring_edge, _ = _validate_clean_route_state(state, classes)
    generator = make_torch_generator((seed + 1) % (2**64), device=state.coordinates.device)
    atom_types = sample_uniform_categories(
        state.mask.atom_mask, classes.num_atom_types, generator=generator
    )
    generative_edge = state.mask.edge_mask & ~ring_pair
    bond_types = sample_uniform_categories(
        generative_edge, classes.num_bond_states, generator=generator
    )
    bond_types = torch.where(
        ring_edge,
        _sample_nonzero_categories(
            ring_edge, classes.num_bond_states, generator=generator
        ),
        bond_types,
    )
    formal_charge_types = torch.where(
        outer_atom,
        sample_uniform_categories(
            outer_atom, classes.num_formal_charge_types, generator=generator
        ),
        state.formal_charge_types,
    )
    chiralities = torch.where(
        outer_atom,
        sample_uniform_categories(
            outer_atom, classes.num_chirality_types, generator=generator
        ),
        state.chiralities,
    )
    initialized = replace(
        state,
        atom_types=atom_types,
        bond_types=bond_types,
        formal_charge_types=formal_charge_types,
        chiralities=chiralities,
    )
    initialized.validate()
    return initialized


def clean_ring_sidechain_state_from_input(
    stage3_input: Stage3Input,
    *,
    timestep: int = 0,
) -> Stage3DiffusionState:
    """Create a clean training state from a converted Route-A input.

    Unlike inference initialization, this function copies the real molecular
    coordinates from ``stage3_input.scaffold.coordinates``. The input should
    first be passed through ``build_route_a_training_batch`` so absent candidate
    pairs are represented by ``NO_BOND=0``.
    """

    if not isinstance(stage3_input, Stage3Input):
        raise TypeError("stage3_input must be a Stage3Input")
    stage3_input.validate()
    if isinstance(timestep, bool) or not isinstance(timestep, int):
        raise TypeError("timestep must be an integer")
    if timestep < 0:
        raise ValueError("timestep must be non-negative")
    graph = stage3_input.scaffold
    if graph.coordinates is None:
        raise ValueError("Route-A clean training input requires real coordinates")
    if (
        stage3_input.mask.ring_atom_mask is None
        or stage3_input.mask.ring_pair_mask is None
        or stage3_input.mask.ring_edge_mask is None
    ):
        raise ValueError("Route-A clean training input requires all ring masks")
    if graph.atom_types is None or graph.bond_types is None:
        raise ValueError("Route-A clean training input requires atom and bond labels")
    if graph.formal_charge_types is None or graph.chiralities is None:
        raise ValueError("Route-A clean training input requires charge and chirality labels")
    state = Stage3DiffusionState(
        atom_features=graph.atom_features.clone(),
        edge_index=graph.edge_index.clone(),
        edge_features=graph.edge_features.clone(),
        coordinates=graph.coordinates.clone(),
        descriptor=stage3_input.descriptor.values.clone(),
        timestep=torch.full(
            (stage3_input.batch_size,),
            timestep,
            dtype=torch.long,
            device=stage3_input.device,
        ),
        mask=BatchMask(
            atom_mask=stage3_input.mask.atom_mask.clone(),
            edge_mask=stage3_input.mask.edge_mask.clone(),
            descriptor_mask=stage3_input.mask.descriptor_mask.clone(),
            pocket_mask=stage3_input.mask.pocket_mask.clone(),
            ring_atom_mask=stage3_input.mask.ring_atom_mask.clone(),
            ring_pair_mask=stage3_input.mask.ring_pair_mask.clone(),
            ring_edge_mask=stage3_input.mask.ring_edge_mask.clone(),
        ),
        metadata=stage3_input.metadata,
        atom_types=graph.atom_types.clone(),
        bond_types=graph.bond_types.clone(),
        formal_charge_types=graph.formal_charge_types.clone(),
        chiralities=graph.chiralities.clone(),
    )
    state.validate()
    return state


def reverse_route_categories(
    state: Stage3DiffusionState,
    *,
    atom_logits: Tensor,
    bond_logits: Tensor,
    formal_charge_logits: Tensor,
    chirality_logits: Tensor,
    timestep: Tensor,
    schedule: DDPMNoiseSchedule,
    classes: RingSidechainClassConfig,
    generator: torch.Generator | None = None,
) -> tuple[Tensor, Tensor, Tensor, Tensor]:
    """Sample one constrained Route-A categorical reverse transition."""

    outer_atom, ring_pair, ring_edge, _ = _route_masks(state)
    atom_types = categorical_reverse_step(
        state.atom_types,
        atom_logits,
        timestep,
        schedule,
        state.mask.atom_mask,
        classes.num_atom_types,
        generator=generator,
    )
    generative_edge = state.mask.edge_mask & ~ring_pair
    bond_types = categorical_reverse_step(
        torch.where(generative_edge, state.bond_types, torch.zeros_like(state.bond_types)),
        bond_logits,
        timestep,
        schedule,
        generative_edge,
        classes.num_bond_states,
        generator=generator,
    )
    shifted_ring = torch.where(ring_edge, state.bond_types - 1, torch.zeros_like(state.bond_types))
    ring_sample = categorical_reverse_step(
        shifted_ring,
        bond_logits[..., 1:],
        timestep,
        schedule,
        ring_edge,
        classes.num_bond_states - 1,
        generator=generator,
    )
    bond_types = torch.where(ring_edge, ring_sample + 1, bond_types)
    formal_charge_types = categorical_reverse_step(
        torch.where(
            outer_atom,
            state.formal_charge_types,
            torch.zeros_like(state.formal_charge_types),
        ),
        formal_charge_logits,
        timestep,
        schedule,
        outer_atom,
        classes.num_formal_charge_types,
        generator=generator,
    )
    formal_charge_types = torch.where(
        outer_atom, formal_charge_types, state.formal_charge_types
    )
    chiralities = categorical_reverse_step(
        torch.where(
            outer_atom,
            state.chiralities,
            torch.zeros_like(state.chiralities),
        ),
        chirality_logits,
        timestep,
        schedule,
        outer_atom,
        classes.num_chirality_types,
        generator=generator,
    )
    chiralities = torch.where(outer_atom, chiralities, state.chiralities)
    return atom_types, bond_types, formal_charge_types, chiralities


